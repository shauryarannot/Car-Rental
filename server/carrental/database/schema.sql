-- Car Rental schema for PostgreSQL
-- Run once on an empty database:
--     psql -U <user> -d postgres -f database/schema.sql
-- Safe to run again: every statement uses IF NOT EXISTS.
-- Column names match the JPA entities (dailyRate -> daily_rate, employeeId -> employee_id, ...).

CREATE TABLE IF NOT EXISTS category (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255)  NOT NULL UNIQUE,
    discount_percent NUMERIC(38,2) DEFAULT 0
        CHECK (discount_percent >= 0 AND discount_percent <= 50)
);

CREATE TABLE IF NOT EXISTS vehicle (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)  NOT NULL,
    daily_rate  NUMERIC(38,2) NOT NULL CHECK (daily_rate > 0),
    available   BOOLEAN       NOT NULL DEFAULT TRUE,
    category_id BIGINT        NOT NULL REFERENCES category(id)
);

CREATE TABLE IF NOT EXISTS customer (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    phone       VARCHAR(255),
    employee_id VARCHAR(255),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    password    VARCHAR(255),                          -- BCrypt hash, NULL for customers without a login
    role        VARCHAR(255) NOT NULL DEFAULT 'CUSTOMER'
                CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

-- For a database created before authentication was added
ALTER TABLE customer ADD COLUMN IF NOT EXISTS password VARCHAR(255);
ALTER TABLE customer ADD COLUMN IF NOT EXISTS role VARCHAR(255) NOT NULL DEFAULT 'CUSTOMER';

CREATE TABLE IF NOT EXISTS discount_coupon (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(255)  NOT NULL UNIQUE,
    coupon_type      VARCHAR(255)  NOT NULL
        CHECK (coupon_type IN ('FIRST_RENTAL', 'DURATION', 'EMPLOYEE')),
    discount_percent NUMERIC(38,2) NOT NULL
        CHECK (discount_percent > 0 AND discount_percent <= 50),
    min_days         INTEGER,
    max_days         INTEGER,
    CHECK (min_days IS NULL OR (min_days >= 1 AND max_days <= 30 AND min_days <= max_days))
);

CREATE TABLE IF NOT EXISTS rental (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT        NOT NULL REFERENCES customer(id),
    vehicle_id       BIGINT        NOT NULL REFERENCES vehicle(id),
    days             INTEGER       NOT NULL CHECK (days >= 1 AND days <= 30),
    start_date       DATE,
    end_date         DATE,
    status           VARCHAR(255)  CHECK (status IN ('ACTIVE', 'COMPLETED')),
    benefit_type     VARCHAR(255)  CHECK (benefit_type IN ('NONE', 'COUPON', 'CATEGORY_DISCOUNT', 'FREE_UPGRADE')),
    coupon_code      VARCHAR(255),
    discount_percent NUMERIC(38,2),
    total_amount     NUMERIC(38,2)
);

-- Indexes on the columns used for joins and lookups
CREATE INDEX IF NOT EXISTS idx_vehicle_category  ON vehicle(category_id);
CREATE INDEX IF NOT EXISTS idx_vehicle_available ON vehicle(available);
CREATE INDEX IF NOT EXISTS idx_rental_customer   ON rental(customer_id);
CREATE INDEX IF NOT EXISTS idx_rental_vehicle    ON rental(vehicle_id);